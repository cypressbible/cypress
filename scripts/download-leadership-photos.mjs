/**
 * Download leadership portraits from cypressbible.org/leadership/
 * and write src/data/leadership-photos.ts
 *
 * Usage: node scripts/download-leadership-photos.mjs
 */

import fs from "fs";
import https from "https";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const outDir = path.join(root, "public/images/leadership");

const BAD_SUBSTRINGS = ["psalm-119-1.jpg", "placeholder.png"];

function fetchText(u) {
  return new Promise((resolve, reject) => {
    https
      .get(
        u,
        { headers: { "User-Agent": "Mozilla/5.0 (compatible; CypressStaticSiteBot/1.0)" } },
        (res) => {
          if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
            const next = new URL(res.headers.location, u).href;
            resolve(fetchText(next));
            return;
          }
          let body = "";
          res.on("data", (c) => (body += c));
          res.on("end", () => resolve(body));
        }
      )
      .on("error", reject);
  });
}

function clean(s) {
  return s.replace(/&amp;/g, "&").trim();
}

function nameSlug(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function downloadFile(url, dest) {
  return new Promise((resolve, reject) => {
    const file = fs.createWriteStream(dest);
    https
      .get(
        url,
        { headers: { "User-Agent": "Mozilla/5.0 (compatible; CypressStaticSiteBot/1.0)" } },
        (res) => {
          if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
            file.close();
            fs.unlink(dest, () => {});
            const next = new URL(res.headers.location, url).href;
            downloadFile(next, dest).then(resolve).catch(reject);
            return;
          }
          if (res.statusCode !== 200) {
            file.close();
            fs.unlink(dest, () => {});
            reject(new Error(`HTTP ${res.statusCode}`));
            return;
          }
          res.pipe(file);
          file.on("finish", () => {
            file.close((e) => (e ? reject(e) : resolve()));
          });
        }
      )
      .on("error", (err) => {
        try {
          file.close();
          fs.unlink(dest, () => {});
        } catch {
          //
        }
        reject(err);
      });
  });
}

const PAGE = "https://cypressbible.org/leadership/";
const tsOut = path.join(root, "src/data/leadership-photos.ts");

const html = await fetchText(PAGE);
const parts = html.split('<div class="ova-our-team">').slice(1);
const byName = new Map();

for (const block of parts) {
  const imgTag = block.match(/<img\b[^>]*>/i);
  if (!imgTag) continue;
  const t = imgTag[0];
  const srcM = t.match(/\bsrc\s*=\s*["']([^"']+)["']/i);
  const altM = t.match(/\balt\s*=\s*["']([^"']*)["']/i);
  if (!srcM) continue;
  const rawSrc = clean(srcM[1]).split("?")[0];
  const alt = altM ? clean(altM[1]) : "";
  if (!alt || !rawSrc.includes("cypressbible.org")) continue;
  if (BAD_SUBSTRINGS.some((b) => rawSrc.includes(b))) continue;
  if (!byName.has(alt)) byName.set(alt, rawSrc);
}

fs.mkdirSync(outDir, { recursive: true });

/** @type {Record<string,string>} */
const mapping = {};

for (const [name, srcUrl] of byName) {
  const slug = nameSlug(name);
  const urlPath = new URL(srcUrl).pathname;
  let ext = path.extname(urlPath).toLowerCase();
  if (!ext || ext.length > 5) ext = ".jpg";
  const filename = `${slug}${ext}`;
  const destFs = path.join(outDir, filename);
  try {
    await downloadFile(srcUrl, destFs);
    mapping[name] = `/images/leadership/${filename}`;
    console.error("saved", filename);
  } catch (e) {
    console.error("skip failed download", name, e.message || e);
  }
}

const sortedKeys = Object.keys(mapping).sort((a, b) => a.localeCompare(b));

const tsBody = `/**
 * Staff portrait paths (local). Generated by scripts/download-leadership-photos.mjs — re-run after updating CBC photos.
 * Names missing here use initials placeholder in the UI.
 */
export const staffPhotos: Record<string, string> = {
${sortedKeys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(mapping[k])}`).join(",\n")}
};
`;

fs.writeFileSync(tsOut, tsBody, "utf8");
console.error("wrote", tsOut, "photos:", sortedKeys.length);
